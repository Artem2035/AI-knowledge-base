"""
Статические промпт-константы роли Synthesizer+Writer (два шага
map-reduce: планирование структуры заметок и запись текста каждой
заметки — см. roles/synthesizer_writer.py). Вынесены сюда без изменения
содержания, см. gemini/prompts/planner.py про принцип разделения.
"""
from __future__ import annotations

# ---------------------------------------------------------------------------
# Шаг 1 — Writer: по одному вызову на КАЖДУЮ заметку из плана. Получает
# только evidence, назначенный этой заметке (а не весь список), поэтому
# промпт на порядок меньше, чем был в одном большом вызове.
# ---------------------------------------------------------------------------

# Блок форматирования вынесен в отдельную константу (а не вплетён единым
# куском в WRITE_SYSTEM_INSTRUCTION), чтобы его можно было переиспользовать
# отдельно (например, для будущей роли "reformat existing note") и чтобы
# при правках форматирования не задевать остальную часть инструкции по
# содержанию/ссылкам/языку.
#
# Принцип: элементы форматирования (callout, списки, код) — это
# ИНСТРУМЕНТЫ ПО СМЫСЛУ, а не обязательный чек-лист на каждую заметку.
# Явно НЕТ пункта "используй минимум N элементов" — предыдущая версия
# промпта требовала фиксированную структуру (обязательный callout в
# начале, обязательный нумерованный и маркированный список и т.д.), из-за
# чего модель добавляла притянутые списки из одного пункта и пустые
# предупреждения там, где по содержанию их не было — то есть подгоняла
# материал под форму вместо обратного.
FORMATTING_GUIDANCE = (
    "ФОРМАТИРОВАНИЕ (Obsidian Flavored Markdown):\n\n"
    "Помимo обычного текста, подзаголовков ## и блоков кода тебе доступны "
    "следующие элементы. Используй их НЕ по обязательному шаблону, а "
    "только там, где они действительно уместны по содержанию конкретной "
    "заметки:\n\n"
    "— Callout (` > [!type] Заголовок`, далее строки текста тоже начинаются "
    "с `>`): [!abstract] — если у темы есть смысл дать краткое резюме перед "
    "деталями (не нужен для короткой заметки, где резюме дублировало бы "
    "сам текст); [!warning] — если в материале есть реальная частая ошибка "
    "или неочевидное поведение, которое стоит выделить; [!tip] — если есть "
    "конкретный практический совет; [!info] — для важного уточнения "
    "контекста, которое прервало бы основной текст. Не создавай callout "
    "ради разнообразия — пустой или притянутый callout хуже, чем его "
    "отсутствие.\n"
    "— Нумерованный список — только если в материале РЕАЛЬНО есть "
    "последовательность шагов, этапов алгоритма или порядок, важный по "
    "смыслу. Не превращай в нумерованный список то, что не упорядочено.\n"
    "— Маркированный список — для перечисления однородных фактов, "
    "характеристик, вариантов, спецсимволов и т.п. Не дроби на список "
    "обычный связный текст без необходимости.\n"
    "— Выделения: **жирный** — для ключевых терминов и важных утверждений; "
    "`инлайн-код` — для имён функций/методов/переменных, спецсимволов, "
    "путей; курсив — для смыслового акцента, использовать умеренно.\n"
    "— Блоки кода с указанием языка (```python и т.п.) — только если "
    "пример действительно иллюстрирует техническую деталь темы.\n\n"
    "Не обязан использовать все перечисленные элементы в каждой заметке — "
    "их количество и состав определяются содержанием, а не требованием "
    "разнообразия форматирования."
)

